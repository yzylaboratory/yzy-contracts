from __future__ import annotations

from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.core.config import SUPPORTED_OCR_LANGUAGES

SupportedContentType = Literal[
    "application/pdf",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
]

OcrMode = Literal["auto", "on", "off"]


class DocumentInput(BaseModel):
    model_config = ConfigDict(extra="forbid")

    filename: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Original file name of the contract document (.pdf or .docx).",
        examples=["contrato_servicios.pdf"],
    )
    content_type: str = Field(
        ...,
        min_length=1,
        max_length=150,
        description="MIME type of the document.",
        examples=["application/pdf"],
    )
    download_url: str = Field(
        ...,
        min_length=8,
        max_length=4096,
        description="Presigned HTTPS URL pointing to Cloudflare R2.",
        examples=[
            "https://contracts.r2.cloudflarestorage.com/users/123/contrato_servicios.pdf?X-Amz-Signature=example"
        ],
    )


class ExtractionOptions(BaseModel):
    model_config = ConfigDict(extra="forbid")

    ocr_mode: OcrMode = Field(
        default="auto",
        description="OCR strategy: 'auto' (run OCR when needed), 'on' (force full-page OCR), or 'off' (disable OCR).",
        examples=["auto"],
    )
    ocr_languages: list[str] = Field(
        default_factory=lambda: ["es", "en"],
        min_length=1,
        max_length=5,
        description="Prioritized list of ISO 639-1 OCR language codes.",
        examples=[["es", "en"]],
    )
    extract_tables: bool = Field(
        default=True,
        description="Whether to run table structure recognition on the document.",
        examples=[True],
    )

    @field_validator("ocr_languages")
    @classmethod
    def validate_languages(cls, value: list[str]) -> list[str]:
        normalized: list[str] = []
        for raw in value:
            code = raw.strip().lower()
            if code not in SUPPORTED_OCR_LANGUAGES:
                raise ValueError(
                    f"Unsupported OCR language '{raw}'. Supported languages: {sorted(SUPPORTED_OCR_LANGUAGES)}."
                )
            if code not in normalized:
                normalized.append(code)
        if not normalized:
            raise ValueError("ocr_languages must contain at least one language.")
        return normalized


class ExtractionRequest(BaseModel):
    model_config = ConfigDict(
        extra="forbid",
        json_schema_extra={
            "examples": [
                {
                    "job_id": "ae17c335-55bc-401a-a46a-391dc7b54d8b",
                    "document": {
                        "filename": "contrato_servicios.pdf",
                        "content_type": "application/pdf",
                        "download_url": "https://example.r2.cloudflarestorage.com/contracts/contrato_servicios.pdf?X-Amz-Algorithm=AWS4-HMAC-SHA256&X-Amz-Expires=300",
                    },
                    "options": {
                        "ocr_mode": "auto",
                        "ocr_languages": ["es", "en"],
                        "extract_tables": True,
                    },
                }
            ]
        },
    )

    job_id: UUID = Field(
        ...,
        description="Correlation identifier generated by the Rust API.",
        examples=["ae17c335-55bc-401a-a46a-391dc7b54d8b"],
    )
    document: DocumentInput
    options: ExtractionOptions = Field(default_factory=ExtractionOptions)


class DocumentSummary(BaseModel):
    model_config = ConfigDict(extra="forbid")

    filename: str = Field(..., examples=["contrato_servicios.pdf"])
    content_type: SupportedContentType = Field(..., examples=["application/pdf"])
    page_count: int | None = Field(
        default=None,
        ge=1,
        description="Number of pages when reliably known (nullable for DOCX or when unavailable).",
        examples=[5],
    )


class ExtractionMetadata(BaseModel):
    model_config = ConfigDict(extra="forbid")

    tables_detected: int = Field(
        ...,
        ge=0,
        description="Count of structured tables detected in the document.",
        examples=[2],
    )
    ocr_used: bool | None = Field(
        default=None,
        description="Whether OCR was applied during conversion, or null if not determinable.",
        examples=[False],
    )
    duration_ms: int = Field(
        ...,
        ge=0,
        description="Total extraction wall-clock time in milliseconds.",
        examples=[1840],
    )


class ExtractionWarningItem(BaseModel):
    model_config = ConfigDict(extra="forbid")

    code: str = Field(
        ...,
        description="Machine-readable warning code.",
        examples=["LOW_TEXT_DENSITY"],
    )
    message: str = Field(
        ...,
        description="Human-readable explanation of what should be manually reviewed.",
        examples=["Some pages yielded very little text; verify scanned clauses manually."],
    )


class ExtractionResultPayload(BaseModel):
    model_config = ConfigDict(extra="forbid")

    markdown: str = Field(
        ...,
        min_length=1,
        description="Normalized Markdown extracted from the document.",
        examples=["# CONTRATO DE SERVICIOS\n\nEntre las partes..."],
    )
    metadata: ExtractionMetadata
    warnings: list[ExtractionWarningItem] = Field(
        default_factory=list,
        description="Non-fatal extraction warnings requiring human review.",
    )


class ExtractionResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    job_id: UUID = Field(..., examples=["ae17c335-55bc-401a-a46a-391dc7b54d8b"])
    status: Literal["completed"] = Field(default="completed", examples=["completed"])
    document: DocumentSummary
    extraction: ExtractionResultPayload


class HealthResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    status: Literal["ok"] = "ok"
    service: str = Field(default="doc-extractor-api", examples=["doc-extractor-api"])
    version: str = Field(default="0.1.0", examples=["0.1.0"])


class ReadinessResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    status: Literal["ready", "not_ready"] = "ready"
    service: str = Field(default="doc-extractor-api", examples=["doc-extractor-api"])
    checks: dict[str, bool] = Field(
        default_factory=dict,
        examples=[{"config_valid": True, "converter_ready": True}],
    )
