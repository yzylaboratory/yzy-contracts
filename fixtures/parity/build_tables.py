"""Generates services/api/src/modules/document_fill/tables.rs from the portal sources.

The tables are the portal's data, not a copy of its logic: reviewed body fingerprints
(`reference-word.ts`), company paragraph ranges (`company-reference-ranges.ts`), shared
clause defaults and labels (`company-fields.ts`). Rerun after the portal changes those files:

    python3 -I fixtures/parity/build_tables.py

Every value comes from the portal source. Nothing is typed by hand.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
PORTAL = ROOT / "apps/portal/app"
OUT = ROOT / "services/api/src/modules/document_fill/tables.rs"


def read(path):
    return (PORTAL / path).read_text(encoding="utf-8")


def rust_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def model_variant(key):
    return "".join(part.capitalize() for part in key.split("_"))


def reviewed_bodies():
    source = read("contratos/reference-word.ts")
    block = source.split("const referenceBodies = {", 1)[1].split("} as const;", 1)[0]
    pairs = re.findall(r'"([0-9a-f]{64})":\s*"([a-z_]+)"', block)
    insurance = re.search(r'const insuranceSaleBody = "([0-9a-f]{64})"', source).group(1)
    pairs.append((insurance, "venta_condicional_seguro"))
    return pairs


def company_ranges():
    source = read("contratos/company-reference-ranges.ts")
    block = source.split("export const companyReferenceRanges", 1)[1]
    models = {}
    current = None
    for line in block.splitlines():
        header = re.match(r"^  ([a-z_]+): \[$", line)
        if header:
            current = header.group(1)
            models[current] = []
            continue
        entry = re.search(r'\{ paragraph: (\d+), start: (\d+), end: (\d+), key: "([a-z_]+)" \}', line)
        if entry and current:
            models[current].append((int(entry.group(1)), int(entry.group(2)), int(entry.group(3)), entry.group(4)))
    return models


def clause_defaults():
    source = read("configuracion/empresas/company-fields.ts")
    block = source.split("export const companyClauseDefaults: Record<string, string> = {", 1)[1].split("};", 1)[0]
    return re.findall(r'^\s*(empresa_[a-z0-9_]+): "((?:[^"\\]|\\.)*)",?$', block, re.M)


def clause_markers():
    source = read("configuracion/empresas/company-fields.ts")
    block = source.split("const contractClauseMarkers = {", 1)[1].split("} as const", 1)[0]
    return re.findall(r"^\s*([a-z_]+): \"(empresa_[a-z0-9_]+)\",?$", block, re.M)


def company_labels():
    source = read("configuracion/empresas/company-fields.ts")
    labels = dict()
    for key, label in re.findall(r'key: "(empresa_[a-z0-9_]+)",\s*label: "((?:[^"\\]|\\.)*)"', source):
        labels.setdefault(key, label)
    if re.search(r"\{\s*key: companyNameKey,\s*label:", source):
        label = re.search(r"\{\s*key: companyNameKey,\s*label: \"([^\"]+)\"", source).group(1)
        labels.setdefault("empresa_razon_social", label)
    return sorted(labels.items())


def main():
    bodies = reviewed_bodies()
    ranges = company_ranges()
    defaults = clause_defaults()
    markers = clause_markers()
    labels = company_labels()
    lines = [
        "//! Generated by `fixtures/parity/build_tables.py` from the portal sources. Do not edit by hand.",
        "",
        "use super::reviewed::ReviewedModel;",
        "",
        "/// SHA-256 of `word/document.xml` for each reviewed body (`reference-word.ts`).",
        "pub(super) const REVIEWED_BODIES: &[(&str, ReviewedModel)] = &[",
    ]
    for digest, key in bodies:
        lines.append(f"    ({rust_str(digest)}, ReviewedModel::{model_variant(key)}),")
    lines += ["];", ""]

    lines += [
        "/// One company-owned span of a reviewed body (`company-reference-ranges.ts`).",
        "/// `paragraph` indexes the document's paragraphs, `start` and `end` are UTF-16 offsets.",
        "pub(super) struct CompanyRange {",
        "    pub paragraph: usize,",
        "    pub start: usize,",
        "    pub end: usize,",
        "    pub key: &'static str,",
        "}",
        "",
    ]
    for key, entries in ranges.items():
        lines.append(f"const RANGES_{key.upper()}: &[CompanyRange] = &[")
        for paragraph, start, end, field in entries:
            lines.append(
                f"    CompanyRange {{ paragraph: {paragraph}, start: {start}, end: {end}, key: {rust_str(field)} }},"
            )
        lines += ["];", ""]
    lines += [
        "pub(super) fn company_ranges(model: ReviewedModel) -> &'static [CompanyRange] {",
        "    match model {",
    ]
    for key in ranges:
        lines.append(f"        ReviewedModel::{model_variant(key)} => RANGES_{key.upper()},")
    lines += [
        "        _ => &[],",
        "    }",
        "}",
        "",
        "/// Shared clause defaults used when a company profile omits a key (`companyClauseDefaults`).",
        "pub(super) const CLAUSE_DEFAULTS: &[(&str, &str)] = &[",
    ]
    for key, value in defaults:
        lines.append(f"    ({rust_str(key)}, {rust_str(value)}),")
    lines += [
        "];",
        "",
        "/// Word markers that map to company profile keys (`contractClauseMarkers`).",
        "pub(super) const CONTRACT_CLAUSE_MARKERS: &[(&str, &str)] = &[",
    ]
    for marker, key in markers:
        lines.append(f"    ({rust_str(marker)}, {rust_str(key)}),")
    lines += [
        "];",
        "",
        "/// Labels of the company fields shown in the portal (`companyFieldGroups`).",
        "pub(super) const COMPANY_LABELS: &[(&str, &str)] = &[",
    ]
    for key, label in labels:
        lines.append(f"    ({rust_str(key)}, {rust_str(label)}),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"tables: {len(bodies)} bodies, {sum(len(v) for v in ranges.values())} ranges, "
          f"{len(defaults)} defaults, {len(markers)} markers, {len(labels)} labels")


if __name__ == "__main__":
    main()
